import json, mlib
mlib.set_warm(0.1)
T, F = mlib.load_targets()
from fit_styles import ORDER, BASE
P = json.load(open('fit_params.json'))
FIELDS = "kind,g0,g100,gamma,knee,b0,b100,preHp,prePkF,prePkDb,prePkQ,postPkF,postPkDb,postPkQ,postLp,postLpOrder,s0,s100,knee2,c0,c50,c100".split(',')
def makeup(d, name):
    dd = dict(d); dd['c0'] = dd['c50'] = dd['c100'] = 0.0
    for dr, key in ((0.0,'c0'),(0.5,'c50'),(1.0,'c100')):
        d[key] = T[name][dr]['fund'] - mlib.measure(dd, dr)['fund']
    return d
rows = []
for n in ORDER:
    if n in P and P[n]['params'] is not None:
        d = dict(BASE); d.update(P[n]['params'])
    else:
        d = dict(BASE)
    if n == 'Destroy': d['s100'] = 3.6; d = makeup(d, n)
    if n == 'Smudge':  d.update(kind=5, s0=0, s100=1, g0=0, g100=0, knee=2); d = makeup(d, n)
    if n == 'Rectify':
        d.update(kind=2, g0=0, g100=12, knee=2, s0=0, s100=1)
        dd = dict(d); dd['c0'] = dd['c50'] = dd['c100'] = 0.0
        for dr, key in ((0.0,'c0'),(0.5,'c50'),(1.0,'c100')):
            m = mlib.measure(dd, dr); t = T[n][dr]
            d[key] = (t['fund'] + t['H'][2]) - (m['fund'] + m['H'][2])
    if n in ('Destroy','Smudge','Rectify'):
        for dr in (0, .5, 1):
            m = mlib.measure(d, dr); t = T[n][dr]
            print(n, dr, 'fund %.1f/%.1f thd %.1f/%.1f H2 %.1f/%.1f H3 %.1f/%.1f' % (m['fund'], t['fund'], m['thd'], t['thd'], m['H'][2], t['H'][2], m['H'][3], t['H'][3]))
    rows.append(d)
with open('../Source/StyleTable.h', 'w') as f:
    f.write('// Generated by fit/gen_table.py from black-box measurements. Do not edit by hand.\n#pragma once\n#include "StyleEngine.h"\n\n')
    f.write('static const char* const kStyleNames[] = {\n' + ',\n'.join('    "%s"' % n for n in ORDER) + '\n};\n')
    f.write('static const nep::StyleDef kStyles[%d] = {\n' % len(ORDER))
    for n, d in zip(ORDER, rows):
        vals = [str(int(d[k])) if k in ('kind','postLpOrder') else repr(float(d[k])) for k in FIELDS]
        f.write('    { %s }, // %s\n' % (', '.join(vals), n))
    f.write('};\n\n// measured reference: fundamental dB, THD %%, H2,H3,H4,H5,H7 dBc at drive 0/50/100 %%\n')
    f.write('struct StyleTarget { double fund, thd, h[5]; };\nstatic const StyleTarget kStyleTargets[%d][3] = {\n' % len(ORDER))
    for n in ORDER:
        f.write('    { ' + ', '.join('{ %.2f, %.2f, { %s } }' % (T[n][dr]['fund'], T[n][dr]['thd'], ', '.join('%.1f' % max(T[n][dr]['H'][h], -200) for h in (2,3,4,5,7))) for dr in (0.0,0.5,1.0)) + ' }, // %s\n' % n)
    f.write('};\n')
